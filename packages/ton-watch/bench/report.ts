/**
 * Renders bench/results/*.json into bench/RESULTS.md.
 *
 *   bun run bench/report.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fmt, loadResult } from "./lib";

const out: string[] = ["# Benchmark results", "", "Generated by `bun run bench/report.ts` from `bench/results/*.json`. All runs against mainnet public liteservers from one machine.", ""];

const depth = loadResult("archive-depth");
if (depth) {
  out.push(
    "## How far back public liteservers serve account history",
    "",
    `Measured ${depth.measuredAt.slice(0, 10)}: \`getTransactions\` for real transactions of \`${depth.address}\` at each age. ✓ served, · pruned.`,
    "",
    depth.table,
    ""
  );
}

const backfill = loadResult("backfill");
if (backfill) {
  out.push("## Backfill throughput", "");
  for (const [label, r] of Object.entries<any>(backfill)) {
    if (label === "smoke") continue;
    out.push(
      `### ${label} (${r.measuredAt.slice(0, 16).replace("T", " ")}, window: last ${r.hours}h)`,
      "",
      "| addresses | concurrency | split | tx | seconds | tx/s | calls | calls/s | complete |",
      "|---:|---:|:---:|---:|---:|---:|---:|---:|:---:|",
      ...r.runs.map(
        (x: any) =>
          `| ${x.size} | ${x.concurrency} | ${x.split === false || x.split === undefined ? "off" : "on"} | ${x.txs} | ${fmt(x.seconds)} | ${fmt(x.txPerSecond)} | ${x.calls} | ${fmt(x.callsPerSecond)} | ${x.complete} |`
      ),
      ""
    );
  }
}

const scan = loadResult("block-scan");
if (scan) {
  out.push("## Baseline: scan every masterchain block", "");
  for (const [label, r] of Object.entries<any>(scan)) {
    out.push(
      `### ${label} (${r.measuredAt.slice(0, 16).replace("T", " ")}, window: last ${r.hours}h)`,
      "",
      "| addresses | concurrency | mc blocks | shard blocks | chain tx | watched tx | seconds | tx/s | calls | calls/s | calls/mc block |",
      "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
      ...r.runs.map(
        (x: any) =>
          `| ${x.size} | ${x.concurrency} | ${x.mcBlocks} | ${x.shardBlocks} | ${x.chainTxs ?? "—"} | ${x.txs} | ${fmt(x.seconds)} | ${fmt(x.txPerSecond)} | ${x.calls} | ${fmt(x.callsPerSecond)} | ${fmt(x.callsPerMcBlock)} |`
      ),
      ""
    );
  }
}

const outage = loadResult("outage");
if (outage) {
  out.push(
    "## Catch-up after an outage (10 busy addresses)",
    "",
    "| run | outage | split | store | tx | minutes | tx/s | calls | calls/s | complete | stuck ranges |",
    "|---|---:|:---:|---|---:|---:|---:|---:|---:|:---:|---:|",
    ...Object.entries<any>(outage).map(
      ([k, x]) =>
        `| ${k} | ${x.days}d | ${x.split ? "on" : "off"} | ${x.store} | ${x.txs} | ${fmt(x.seconds / 60)}${x.timedOut ? " (limit)" : ""} | ${fmt(x.txPerSecond)} | ${x.calls} | ${fmt(x.callsPerSecond)} | ${x.completeAddresses}/10 | ${x.stuckRanges} |`
    ),
    ""
  );
}

const idle = loadResult("idle");
if (idle) {
  out.push("## Idle cost", "");
  for (const [label, r] of Object.entries<any>(idle)) {
    out.push(
      `### ${label} (${r.measuredAt.slice(0, 16).replace("T", " ")})`,
      "",
      "| detection | addresses | minutes | calls/min | tx indexed meanwhile | lag p50 | lag p99 |",
      "|---|---:|---:|---:|---:|---:|---:|",
      ...r.runs.map(
        (x: any) =>
          `| ${x.detect} | ${x.addresses} | ${fmt(x.minutes)} | ${fmt(x.callsPerMinute)} | ${x.txIndexed} | ${x.lagSecondsP50}s | ${x.lagSecondsP99}s |`
      ),
      ""
    );
  }
}

const file = join(import.meta.dir, "RESULTS.md");
writeFileSync(file, out.join("\n"));
console.log(`wrote ${file}`);
